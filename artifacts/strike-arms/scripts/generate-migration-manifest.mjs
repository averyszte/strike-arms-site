/**
 * Write src/lib/migration-manifest.ts from the files in supabase/migrations.
 *
 * The admin Settings screen compares this list against what the database says
 * it has applied (migration 016). For that comparison to mean anything the
 * repo side has to be the repo, not a list somebody remembered to update --
 * so it is generated, and generated as part of `build`, which means a deploy
 * cannot ship a stale one.
 *
 * The migrations live above the Vite root, so import.meta.glob cannot reach
 * them and this cannot be done at bundle time.
 *
 * Run: pnpm --filter @workspace/strike-arms run build (or ... run manifest)
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, '..');
const MIGRATIONS = resolve(ROOT, '../../supabase/migrations');
const OUTPUT = resolve(ROOT, 'src/lib/migration-manifest.ts');

/** `014_grant_audit.sql` -> version `014`, name `grant_audit`. */
const FILENAME = /^(\d+)_(.+)\.sql$/;

function readMigrations() {
  const files = readdirSync(MIGRATIONS)
    .filter((name) => name.endsWith('.sql'))
    .sort();

  return files.map((file) => {
    const match = FILENAME.exec(file);
    if (!match) {
      console.error(
        `manifest: ${file} is not <version>_<name>.sql. The Supabase CLI derives the version it ` +
          'records from that prefix, so a file it cannot parse is one this check cannot see.',
      );
      process.exit(1);
    }
    return { version: match[1], name: match[2], file };
  });
}

function build() {
  const migrations = readMigrations();

  const rows = migrations
    .map((m) => `  { version: '${m.version}', name: '${m.name}', file: '${m.file}' },`)
    .join('\n');

  const source = `// GENERATED by scripts/generate-migration-manifest.mjs -- do not edit.
//
// The migrations present in supabase/migrations at build time. The admin
// Settings screen compares this against applied_migrations() so that "in the
// repo" and "in the database" are the same question with one answer.

export type MigrationFile = {
  /** Numeric prefix. This is what the Supabase CLI records as the version. */
  version: string;
  name: string;
  file: string;
};

export const MIGRATION_MANIFEST: MigrationFile[] = [
${rows}
];
`;

  const existing = (() => {
    try {
      return readFileSync(OUTPUT, 'utf8');
    } catch {
      return '';
    }
  })();

  // Only write on a real change, so a build does not dirty the working tree
  // and invite someone to commit a no-op diff.
  if (existing.replace(/\r\n/g, '\n') === source) {
    console.log(`Migration manifest already current (${migrations.length} migrations).`);
    return;
  }

  writeFileSync(OUTPUT, source, 'utf8');
  console.log(`Wrote ${migrations.length} migrations to src/lib/migration-manifest.ts.`);
}

build();
